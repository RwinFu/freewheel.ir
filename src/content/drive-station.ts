/**
 * «ایستگاه درایو، قطعه به قطعه» — الگوی صفحه‌های کاتالوگ صنعتی.
 *
 * در کاتالوگ‌ها یک تصویر از کل ایستگاه می‌گذارند و رویش شماره؛ کنارش فهرست
 * قطعه‌ها با همان شماره. اینجا همان الگو زنده شده است: هر شماره روی تصویر به
 * ردیف خودش در فهرست وصل است و از آن ردیف به صفحه‌ی همان سری می‌رسیم.
 *
 * دو پیکربندی داریم — نوار نقاله و الواتور — چون جای بک‌استاپ در این دو فرق
 * می‌کند: در نوار نقاله روی شفت سر پولی، و در الواتور روی شفت سر الواتور با
 * اهرمی که به بدنه‌ی کاسه می‌بندد. مختصات نشانگرها (`hot`) درصدی است و روی خودِ
 * تصویر تنظیم شده؛ ترتیب ردیف‌ها هم ترتیب حرکت از موتور به سمت بار است.
 */

export type DrivePoint = {
  /** شماره‌ی قطعه روی تصویر، با رقم فارسی */
  numeral: string;
  title: string;
  /** یک خط: همین قطعه اینجا چه می‌کند */
  role: string;
  /** نقطه‌ی نصب روی ایستگاه */
  position: string;
  /** توضیح کامل‌تر؛ وقتی همان شماره انتخاب شود باز می‌شود */
  detail: string;
  /** عکس واقعی قطعه از آرشیو مشترک سایت */
  image: ProductImage;
  link: { href: string; label: string };
  /** مختصات نشانگر روی تصویر، درصدی از عرض و ارتفاع */
  hot: { x: number; y: number };
};

export type DriveStationData = {
  id: "conveyor" | "elevator";
  /** برچسب زبانه */
  tab: string;
  /** عنوان کوتاه ایستگاه */
  title: string;
  dek: string;
  photo: { src: StaticImageData; alt: string; caption: string; credit: string };
  points: DrivePoint[];
};

